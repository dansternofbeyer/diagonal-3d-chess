"""
bundle_models.py — packs every models/*.glb into models/pieces.js.

Why: a web page opened by double-clicking (a file:// address) is not allowed to
load .glb files with fetch(), but it IS allowed to load a <script> file. So we
store each model as base64 text inside a script the pages can include.

Run it from the project folder after exporting from Blender:
    python3 tools/bundle_models.py

Open source under the MIT License (see ../LICENSE).
"""

import base64
import pathlib

PROJECT_FOLDER = pathlib.Path(__file__).resolve().parent.parent
MODELS_FOLDER = PROJECT_FOLDER / "models"
OUTPUT_FILE = MODELS_FOLDER / "pieces.js"

HEADER = """// pieces.js — every chess piece model as base64 .glb data.
// GENERATED by tools/bundle_models.py from the .glb files in this folder.
// Do not edit by hand: change the models in Blender (blender/pieces.blend or
// blender/build_pieces.py), export, then run the bundle script again.
// Open source under the MIT License (see ../LICENSE).
window.CHESS_PIECE_MODELS = {
"""


def bundle_models():
    model_files = sorted(MODELS_FOLDER.glob("*.glb"))
    lines = [HEADER]
    for model_file in model_files:
        encoded = base64.b64encode(model_file.read_bytes()).decode("ascii")
        lines.append('  "%s": "%s",\n' % (model_file.stem, encoded))
        print("Bundled %-10s %6d bytes" % (model_file.stem, model_file.stat().st_size))
    lines.append("};\n")
    OUTPUT_FILE.write_text("".join(lines))
    print("Wrote", OUTPUT_FILE.relative_to(PROJECT_FOLDER))


if __name__ == "__main__":
    bundle_models()
